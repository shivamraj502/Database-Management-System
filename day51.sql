-- ACID → Properties ensuring transactions execute safely, consistently, and reliably in a database.
-- Serializability → Ensures concurrent transactions produce the same result as serial execution.
-- Deadlock → Situation where transactions wait for each other forever and none can proceed.
-- Locks → Mechanism used to control concurrent access to data and prevent conflicts.