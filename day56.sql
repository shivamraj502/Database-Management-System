-- Practice:
-- When to use NoSQL?


-- SQL vs NoSQL → SQL uses structured tables with fixed schema, while NoSQL uses flexible schema for handling large and unstructured data.
-- Document Database → Stores data as documents like JSON (example: MongoDB).
-- Key-Value Database → Stores data in key-value pairs for very fast lookup (example: Redis).
-- Column Database → Stores data in columns instead of rows, optimized for analytics (example: Apache Cassandra).
-- Graph Database → Stores data as nodes and relationships, useful for connected data (example: Neo4j).
-- When to use NoSQL? → Use NoSQL for big data, high scalability, fast performance, and flexible schema applications like social media or real-time apps.


