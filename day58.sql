-- Questions:
-- WAL
-- RAID
-- Buffer manager
-- NoSQL vs SQL


-- WAL (Write Ahead Logging) → Recovery technique where changes are first written to log before updating the database.
-- RAID → Technology that combines multiple disks to improve performance, reliability, or both.
-- Buffer Manager → DBMS component that manages movement of data pages between disk and memory.
-- NoSQL vs SQL → SQL uses structured tables with fixed schema, while NoSQL uses flexible schema for scalable and unstructured data.