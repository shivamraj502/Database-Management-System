-- Concepts:
-- Serial schedule
-- Concurrent schedule
-- Conflict operations

-- Practice:
-- Check if schedule is conflict serializable.

-- Schedules define the order in which multiple transactions execute in a DBMS, helping manage serial or concurrent execution while avoiding conflicts between operations.
-- They are important for checking conflict serializability, which ensures concurrent transactions produce the same result as serial execution. 