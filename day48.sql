-- Locking Protocols are concurrency control methods that use locks to prevent multiple transactions from causing conflicts while accessing the same data.
-- They ensure safe concurrent execution using Shared locks (read), Exclusive locks (write), and Two-Phase Locking (2PL) for consistency. 💯