-- Concepts:
-- RAID levels
-- Performance vs reliability

-- Practice:
-- Which RAID best for databases?


-- -- RAID Levels → Different methods of combining multiple disks for better performance, storage, and fault tolerance.
-- -- Performance vs Reliability → Higher performance improves speed, while higher reliability improves data safety during failures.
-- -- RAID 0 → Best performance, no fault tolerance.
-- -- RAID 1 → High reliability using disk mirroring.
-- -- RAID 5/10 → Balanced performance and reliability, commonly used in databases.
-- -- Which RAID is best for databases? → RAID 10 is usually best because it provides both high speed and strong fault tolerance.